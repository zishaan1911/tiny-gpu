"""Writes pcb/tiny_gpu.kicad_sch from design.py.

Each symbol sits in its section of the sheet with a short wire and a net label on every
connected pin, and a no-connect flag on every pin left open, so the ERC can check it all.
Run: python schematic.py
"""

import math
import os

import netlist
from sexpr import Sym, dump, find, find_all

OUT = os.path.join(os.path.dirname(__file__), "..", "tiny_gpu.kicad_sch")
G = 2.54
STUB = 2 * G

SECTIONS = [
    ("USB-C, protection and power", ["J1", "R1", "R2", "U1", "U2", "C1", "C2", "U3", "C3", "C4", "R3", "C5", "C6", "D1", "R4", "#FLG01", "#FLG02"]),
    ("USB bridge: FT2232H (A: flash programmer, B: UART to the GPU)", ["U4", "Y1", "C7", "C8", "R5", "R6", "C9", "C10", "C11", "C12", "C13", "C14", "C15", "C16", "C17", "C18", "C19", "U5", "R7", "R8", "R9", "R10", "C20"]),
    ("FPGA: iCE40UP5K running the GPU", ["U6", "C21", "C22", "C23", "C24", "C25", "C26", "C27", "X1", "C29", "D2", "R16"]),
    ("Configuration: SPI flash, reset", ["U7", "R14", "R15", "C28", "R11", "R12", "R13", "SW1"]),
    ("VGA: 4-bit resistor DAC per colour", ["R17", "R18", "R19", "R20", "R21", "R22", "R23", "R24", "R25", "R26", "R27", "R28", "R29", "R30", "J2"]),
    ("Mounting", ["H1", "H2", "H3", "H4"]),
]


def snap(v):
    return round(v / G) * G


def font(size=1.27, bold=False):
    f = [Sym("font"), [Sym("size"), size, size]]
    if bold:
        f.append([Sym("bold"), Sym("yes")])
    return f


def effects(hide=False, justify=None, size=1.27, bold=False):
    e = [Sym("effects"), font(size, bold)]
    if justify:
        e.append([Sym("justify")] + [Sym(j) for j in justify.split()])
    if hide:
        e.append([Sym("hide"), Sym("yes")])
    return e


def prop(name, value, x, y, hide=False, justify=None, angle=0):
    return [Sym("property"), name, value, [Sym("at"), x, y, angle], effects(hide, justify)]


def outward(angle):
    """Direction from a pin's connection point away from the symbol body, in sheet coordinates."""
    a = math.radians(angle)
    return -round(math.cos(a)), round(math.sin(a))


def label_angle(dx, dy):
    return {(-1, 0): 180, (1, 0): 0, (0, -1): 90, (0, 1): 270}[(dx, dy)]


def text_len(s):
    return 1.0 * len(s) + 1.5


def footprint_of(p):
    """Units of a part and the pins on each, with the space each unit needs including labels."""
    units = {}
    for q in p["pin_list"]:
        units.setdefault(q["unit"], []).append(q)
    if not units:
        units = {1: []}
    out = []
    for u, pins in sorted(units.items()):
        if not pins:
            out.append((u, pins, (-5.08, -5.08, 5.08, 5.08)))
            continue
        xs = [q["x"] for q in pins]
        ys = [-q["y"] for q in pins]
        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
        left = right = up = down = 0
        for q in pins:
            dx, dy = outward(q["angle"])
            net = p["nets"].get(q["number"])
            reach = STUB + (text_len(net) if net else 1)
            if dx < 0: left = max(left, reach)
            if dx > 0: right = max(right, reach)
            if dy < 0: up = max(up, reach)
            if dy > 0: down = max(down, reach)
        # Room for the body and the reference and value.
        out.append((u, pins, (x0 - left - 2, y0 - up - 5, x1 + right + 8, y1 + down + 5)))
    return out


def build():
    parts = {p["ref"]: p for p in netlist.resolve()}
    items = []
    lib_ids = []
    width_limit = 760
    y = 30.0
    for title, refs in SECTIONS:
        items.append([Sym("text"), title, [Sym("exclude_from_sim"), Sym("no")], [Sym("at"), 20, y, 0],
                      effects(justify="left bottom", size=3, bold=True), [Sym("uuid"), netlist.uid("title", title)]])
        y += 8
        x = 20.0
        row_h = 0.0
        for ref in refs:
            p = parts[ref]
            if p["lib_id"] not in lib_ids:
                lib_ids.append(p["lib_id"])
            for unit, pins, (bx0, by0, bx1, by1) in footprint_of(p):
                w, h = bx1 - bx0, by1 - by0
                if x + w > width_limit:
                    x = 20.0
                    y += row_h + 6
                    row_h = 0.0
                sx, sy = snap(x - bx0), snap(y - by0)
                items.extend(place(p, unit, pins, sx, sy, by0, by1))
                x += w + 6
                row_h = max(row_h, h)
        y += row_h + 18

    lib = [Sym("lib_symbols")] + [parts_by_lib(parts, lid) for lid in lib_ids]
    sheet = [Sym("kicad_sch"), [Sym("version"), 20250114], [Sym("generator"), "tiny_gpu_gen"],
             [Sym("generator_version"), "1.0"], [Sym("uuid"), netlist.ROOT],
             [Sym("paper"), "User", 800, max(400, math.ceil(y + 20))],
             [Sym("title_block"), [Sym("title"), "Tiny GPU board"], [Sym("rev"), "1"],
              [Sym("comment"), 1, "iCE40UP5K GPU, FT2232H USB link, VGA out. Generated by pcb/gen/schematic.py from design.py."]],
             lib] + items + [[Sym("sheet_instances"), [Sym("path"), "/", [Sym("page"), "1"]]],
                             [Sym("embedded_fonts"), Sym("no")]]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(dump(sheet) + "\n")
    return parts


def parts_by_lib(parts, lib_id):
    return next(p["symbol"] for p in parts.values() if p["lib_id"] == lib_id)


def place(p, unit, pins, sx, sy, top, bottom):
    out = []
    ref = p["ref"]
    two_pin = len(p["pin_list"]) <= 2
    if two_pin:
        rx, ry, vx, vy, just = sx + 3.0, sy - 1.0, sx + 3.0, sy + 1.6, "left"
    else:
        rx, ry, vx, vy, just = sx, sy + top - 2.5, sx, sy + bottom + 2.5, None
    sym = [Sym("symbol"), [Sym("lib_id"), p["lib_id"]], [Sym("at"), sx, sy, 0], [Sym("unit"), unit],
           [Sym("exclude_from_sim"), Sym("no")], [Sym("in_bom"), Sym("yes" if p["bom"] else "no")],
           [Sym("on_board"), Sym("yes" if p["footprint"] else "no")], [Sym("dnp"), Sym("no")],
           [Sym("uuid"), netlist.uid("sym", ref, unit)],
           prop("Reference", ref, rx, ry, hide=ref.startswith("#"), justify=just),
           prop("Value", p["value"], vx, vy, hide=ref.startswith("#"), justify=just),
           prop("Footprint", p["footprint"], sx, sy, hide=True),
           prop("Datasheet", "", sx, sy, hide=True),
           prop("Description", p["note"], sx, sy, hide=True),
           prop("MPN", p["mpn"], sx, sy, hide=True),
           prop("LCSC", p["lcsc"], sx, sy, hide=True)]
    for q in p["pin_list"]:
        sym.append([Sym("pin"), q["number"], [Sym("uuid"), netlist.uid("pin", ref, q["number"])]])
    sym.append([Sym("instances"), [Sym("project"), netlist.PROJECT,
                [Sym("path"), "/" + netlist.ROOT, [Sym("reference"), ref], [Sym("unit"), unit]]]])
    out.append(sym)

    for q in pins:
        px, py = round(sx + q["x"], 4), round(sy - q["y"], 4)
        net = p["nets"].get(q["number"])
        if net is None:
            out.append([Sym("no_connect"), [Sym("at"), px, py], [Sym("uuid"), netlist.uid("nc", ref, q["number"])]])
            continue
        dx, dy = outward(q["angle"])
        ex, ey = round(px + dx * STUB, 4), round(py + dy * STUB, 4)
        out.append([Sym("wire"), [Sym("pts"), [Sym("xy"), px, py], [Sym("xy"), ex, ey]],
                    [Sym("stroke"), [Sym("width"), 0], [Sym("type"), Sym("default")]],
                    [Sym("uuid"), netlist.uid("wire", ref, q["number"])]])
        ang = label_angle(dx, dy)
        just = "left bottom" if ang in (0, 90) else "right bottom"
        # Global labels, so each net keeps its plain name on the board ("VBUS", not "/VBUS").
        just = "left" if ang in (0, 90) else "right"
        out.append([Sym("global_label"), net, [Sym("shape"), Sym("passive")], [Sym("at"), ex, ey, ang],
                    [Sym("fields_autoplaced"), Sym("yes")], effects(justify=just),
                    [Sym("uuid"), netlist.uid("label", ref, q["number"])]])
    return out


if __name__ == "__main__":
    parts = build()
    print(f"wrote {os.path.normpath(OUT)}: {len(parts)} parts")
